import {defineArrayMember, defineField, defineType} from 'sanity'
import {CloudinaryImageInput} from './cloudinaryImageInput'

export const authorType = defineType({
  name: 'author',
  title: 'Author',
  type: 'document',
  fields: [
    defineField({
      name: 'name',
      type: 'string',
    }),
    defineField({
      name: 'slug',
      type: 'slug',
      options: {
        source: 'name',
      },
    }),
    defineField({
      name: 'cloudinaryImageUrl',
      title: 'Cloudinary profile image',
      type: 'url',
      components: {input: CloudinaryImageInput},
    }),
    defineField({
      name: 'bio',
      type: 'array',
      of: [
        defineArrayMember({
          type: 'block',
          styles: [{title: 'Normal', value: 'normal'}],
          lists: [],
        }),
      ],
    }),
  ],
  preview: {
    select: {
      title: 'name',
    },
  },
})
